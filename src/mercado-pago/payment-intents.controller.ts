import {
  Body,
  Controller,
  Get,
  HttpCode,
  HttpStatus,
  Param,
  Post,
  UseGuards,
  UseInterceptors,
} from '@nestjs/common';
import {
  ApiBadRequestResponse,
  ApiBearerAuth,
  ApiConflictResponse,
  ApiCreatedResponse,
  ApiExtraModels,
  ApiForbiddenResponse,
  ApiNotFoundResponse,
  ApiOkResponse,
  ApiOperation,
  ApiParam,
  ApiServiceUnavailableResponse,
  ApiTags,
  ApiUnauthorizedResponse,
} from '@nestjs/swagger';
import type { User } from '@prisma/client';
import { CurrentUser } from '../auth/decorators/current-user.decorator';
import { JwtAuthGuard } from '../auth/guards/jwt-auth.guard';
import { TenantMembershipGuard } from '../auth/guards/tenant-membership.guard';
import { TenantInterceptor } from '../database/tenant.interceptor';
import {
  ProblemDetailsDto,
  ValidationProblemDetailsDto,
} from '../utils/exceptions/dto/problem-details.dto';
import {
  CreatePaymentIntentDto,
  PaymentIntentDto,
} from './dto/payment-intent.dto';
import { PaymentIntentsService } from './payment-intents.service';

/**
 * Cobros con QR de Mercado Pago sobre una estadía.
 *
 * ## Por qué NO es `owner`, a diferencia del resto de `/mercado-pago`
 *
 * `MpAccountsController` restringe sus escrituras a `owner` porque vincular una
 * cuenta es mover A DÓNDE VA LA PLATA. Esto es otra cosa: es cobrarle a un auto
 * que está saliendo, y el que está parado en la barrera a las tres de la mañana
 * es el operario. Pedirle `owner` haría que la playa no pueda cobrar con QR
 * justo cuando el dueño no está, que es la mayor parte del tiempo.
 *
 * El `TenantMembershipGuard` sigue siendo obligatorio: cualquiera con membresía
 * en ESTA playa, ninguno de otra.
 *
 * ## Por qué `cancel` es un `POST` a un sub-recurso y no un `DELETE`
 *
 * Porque no borra nada. Cancelar deja la fila, la mueve a `canceled` y —esto es
 * lo importante— dispara una llamada a Mercado Pago para bajar la orden del QR
 * de la caja. Un `DELETE` prometería que el recurso deja de existir, y acá el
 * historial de cobros intentados se conserva entero.
 */
@ApiTags('Mercado Pago')
@ApiExtraModels(
  ProblemDetailsDto,
  ValidationProblemDetailsDto,
  PaymentIntentDto,
)
@Controller('tenants/:tenantId/payment-intents')
@UseGuards(JwtAuthGuard, TenantMembershipGuard)
@UseInterceptors(TenantInterceptor)
@ApiBearerAuth('bearer')
@ApiParam({
  name: 'tenantId',
  format: 'uuid',
  description: 'ID of the entity (parking lot / tenant).',
})
@ApiUnauthorizedResponse({
  description: 'Missing, malformed, or expired bearer token.',
  type: ProblemDetailsDto,
})
@ApiForbiddenResponse({
  description:
    'The caller is authenticated but is not a member of the `:tenantId` entity.',
  type: ProblemDetailsDto,
})
export class PaymentIntentsController {
  constructor(private readonly intents: PaymentIntentsService) {}

  @Post()
  @ApiOperation({
    operationId: 'paymentIntentsCreate',
    summary: 'Start a QR charge for a stay',
    description: [
      'Creates the payment intent and its Mercado Pago order. The row is persisted BEFORE calling Mercado Pago on purpose: if that call dies on a timeout we do not know whether the order exists, and the `created` state marks exactly that uncertainty.',
      '',
      'The `id` is generated by the client (UUIDv7). Re-sending the same `id` returns the existing intent and does NOT create a second order, which is what makes this endpoint safe to retry.',
      '',
      'The amount is frozen here and never recalculated.',
    ].join('\n'),
  })
  @ApiCreatedResponse({ type: PaymentIntentDto })
  @ApiBadRequestResponse({
    description: 'Invalid payload — bad uuid, or a non-positive amount.',
    type: ValidationProblemDetailsDto,
  })
  @ApiNotFoundResponse({
    description:
      'The stay does not exist in this entity, or the entity has no Mercado Pago account linked (MP_NOT_LINKED).',
    type: ProblemDetailsDto,
  })
  @ApiConflictResponse({
    description: [
      'The charge cannot be started right now:',
      '',
      '- `PAYMENT_INTENT_ALREADY_OPEN` — that stay already has a live charge.',
      '- `PAYMENT_INTENT_POS_BUSY` — the till already has a QR charge in progress for ANOTHER stay. With a static QR the printed sign is bound to one POS and it holds a single order at a time.',
      '- `PAYMENT_INTENT_ENTRY_CLOSED` — the stay already has an exit registered.',
      '- `MP_POS_NOT_PROVISIONED` — the account is linked but has no POS yet; re-sync it.',
      '- `MP_ACCOUNT_TOKEN_EXPIRED`, `MP_ACCOUNT_REVOKED` — the link is not operational.',
    ].join('\n'),
    type: ProblemDetailsDto,
  })
  @ApiServiceUnavailableResponse({
    description: 'Mercado Pago is down or rate-limiting us (MP_UNAVAILABLE).',
    type: ProblemDetailsDto,
  })
  create(
    @Param('tenantId') tenantId: string,
    @CurrentUser() user: User,
    @Body() dto: CreatePaymentIntentDto,
  ): Promise<PaymentIntentDto> {
    return this.intents.create(tenantId, user, dto);
  }

  @Get()
  @ApiOperation({
    operationId: 'paymentIntentsListUnconsumed',
    summary: 'List approved charges that were not applied yet',
    description: [
      'The orphan payments: charges Mercado Pago already credited that have not become a payment transaction yet, newest first.',
      '',
      'They exist because paying and closing the stay are two different moments — the customer pays from the car, the operator closes when done. Money sitting here is real money that will not show up in the till count until somebody applies it.',
    ].join('\n'),
  })
  @ApiOkResponse({ type: [PaymentIntentDto] })
  listUnconsumed(
    @Param('tenantId') tenantId: string,
  ): Promise<PaymentIntentDto[]> {
    return this.intents.listUnconsumed(tenantId);
  }

  @Get(':paymentIntentId')
  @ApiOperation({
    operationId: 'paymentIntentsGetById',
    summary: 'Read one payment intent',
    description: [
      'What the till polls every few seconds while the charge modal is open.',
      '',
      'It also expires the intent lazily: an open intent whose `expiresAt` is in the past is moved to `expired` here. That is defense in depth, not a replacement for the webhook — Mercado Pago does emit `order.expired` for QR, but webhook delivery is best-effort, and a lost one would leave the intent hanging in `pending` forever, which the partial unique index turns into a permanent dead end for that stay and that till.',
    ].join('\n'),
  })
  @ApiParam({
    name: 'paymentIntentId',
    format: 'uuid',
    description: 'ID of the payment intent.',
  })
  @ApiOkResponse({ type: PaymentIntentDto })
  @ApiNotFoundResponse({
    description:
      'No such payment intent in this entity (PAYMENT_INTENT_NOT_FOUND).',
    type: ProblemDetailsDto,
  })
  getById(
    @Param('tenantId') tenantId: string,
    @Param('paymentIntentId') paymentIntentId: string,
  ): Promise<PaymentIntentDto> {
    return this.intents.getById(tenantId, paymentIntentId);
  }

  @Post(':paymentIntentId/cancel')
  @HttpCode(HttpStatus.OK)
  @ApiOperation({
    operationId: 'paymentIntentsCancel',
    summary: 'Cancel a payment intent',
    description: [
      'Cancels the order on the Mercado Pago side too, and that part is not optional: the QR is static, so an order left alive on the till would be paid by the NEXT customer who scans the printed sign — for the previous car amount.',
      '',
      'If Mercado Pago refuses to cancel, the intent is still canceled locally and the failure is audited with `warn` severity. Keeping it alive locally would block the whole till through the partial unique index, and that blockage does not expire on its own; the order left on the Mercado Pago side does.',
    ].join('\n'),
  })
  @ApiParam({
    name: 'paymentIntentId',
    format: 'uuid',
    description: 'ID of the payment intent.',
  })
  @ApiOkResponse({ type: PaymentIntentDto })
  @ApiNotFoundResponse({
    description:
      'No such payment intent in this entity (PAYMENT_INTENT_NOT_FOUND).',
    type: ProblemDetailsDto,
  })
  @ApiConflictResponse({
    description:
      'The intent is no longer open — already paid, expired, canceled or consumed (PAYMENT_INTENT_NOT_CANCELABLE).',
    type: ProblemDetailsDto,
  })
  cancel(
    @Param('tenantId') tenantId: string,
    @Param('paymentIntentId') paymentIntentId: string,
    @CurrentUser() user: User,
  ): Promise<PaymentIntentDto> {
    return this.intents.cancel(tenantId, paymentIntentId, user);
  }
}
