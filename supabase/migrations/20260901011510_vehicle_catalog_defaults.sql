-- Plantilla del catálogo de vehículos.
--
-- Reemplaza al catálogo GLOBAL (las 244 filas con `tenant_id IS NULL` que
-- sembraba 20260831190200). Aquellas eran compartidas y read-only: la playa las
-- veía en su autocompletado pero no podía corregir un nombre ni sacar un modelo
-- que no atiende. Estas no las ve nadie — son la semilla desde la que cada
-- cuenta nueva recibe su copia PROPIA y editable, vía el trigger
-- `bootstrap_tenant_defaults()`.
--
-- Lo que se gana: la plataforma sigue manteniendo un catálogo semilla (sale un
-- modelo nuevo, se agrega acá, y las cuentas nuevas nacen con él) pero deja de
-- poder tocar a las playas existentes, que son dueñas de su catálogo.
--
-- No se expone por la API del tenant y no tiene pantalla de admin: se edita por
-- migración, igual que `vehicle_type_defaults`.

CREATE TABLE vehicle_catalog_defaults (
    brand     varchar(120) NOT NULL,
    model     varchar(120) NOT NULL,
    -- FK a la plantilla de tipos: el generador no puede emitir un type_name
    -- inexistente, y la resolución por nombre dentro del trigger es segura.
    type_name varchar(60) NOT NULL
              REFERENCES vehicle_type_defaults(name) ON UPDATE CASCADE,
    PRIMARY KEY (brand, model)
);

ALTER TABLE vehicle_catalog_defaults ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON vehicle_catalog_defaults FROM anon, authenticated;
